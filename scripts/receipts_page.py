"""Build the login-free "receipts" page (GitLab Pages) from the project's own records.

One static HTML page per project, generated by the ``pages`` job on every main pipeline: every ``autopilot``
issue with its journey card numbers (lead time, human actions after filing, CI footprint), its merge request,
the narrative, every ``security-fix`` merge request and every incident — each cell a link to the GitLab page
it was read from, so a judge can check any number without signing in. Nothing here is typed by hand:
``render()`` only formats what the API returned (``receipts.json`` next to the page is the raw input).

    python scripts/receipts_page.py --out public          # in CI (AUTOPILOT_TOKEN reads notes; GETs are public)
"""

from __future__ import annotations

import argparse
import html
import json
import os
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

from gitlab_api import GitLab, warn

_LEAD = re.compile(r"\*\*Lead time:\*\*.*?= \*\*(.+?)\*\*")
_TOUCH = re.compile(r"\*\*Human actions after filing:\*\* \*\*(\d+)\*\*")
_SCI = re.compile(r"\*\*CI footprint \(estimate\):\*\* (.+?) runner-minutes .*?\*\*(.+?) gCO2e\*\*")
_STAGES = re.compile(r"\*\*(\d+)/9 stages touched\*\*")


def card_numbers(body: str) -> dict:
    """Pull the comparable numbers out of a journey-card note body."""
    out: dict = {}
    if m := _LEAD.search(body):
        out["lead_time"] = m.group(1)
    if m := _TOUCH.search(body):
        out["human_actions"] = int(m.group(1))
    if m := _SCI.search(body):
        out["runner_minutes"] = m.group(1)
        out["g_co2e"] = m.group(2)
    if m := _STAGES.search(body):
        out["stages"] = int(m.group(1))
    return out


def collect(gl: GitLab) -> dict:
    """Read issues, merge requests, incidents and (with a token) the notes that carry the cards."""
    web = gl.project_web_url()
    data: dict = {"project": web, "generated_at": datetime.now(UTC).isoformat(timespec="seconds"), "journeys": []}
    issues = gl.get_all("issues", labels="autopilot", state="all", order_by="created_at", sort="asc")
    for issue in issues:
        if issue.get("issue_type") == "incident":
            continue
        row: dict = {
            "iid": issue["iid"],
            "title": issue["title"],
            "url": issue["web_url"],
            "author": (issue.get("author") or {}).get("username", ""),
            "created_at": issue.get("created_at"),
            "closed_at": issue.get("closed_at"),
            "state": issue.get("state"),
        }
        try:
            mrs = gl.get(f"issues/{issue['iid']}/closed_by")
            mr = next((m for m in mrs if m.get("state") == "merged"), mrs[0] if mrs else None)
            if mr:
                row["mr"] = {
                    "iid": mr["iid"],
                    "url": mr["web_url"],
                    "merged_at": mr.get("merged_at"),
                    "state": mr["state"],
                }
        except Exception as exc:  # noqa: BLE001
            warn(f"closed_by for #{issue['iid']}: {type(exc).__name__}")
        try:
            notes = gl.get_all(f"issues/{issue['iid']}/notes", sort="asc")
            for n in notes:
                body = n.get("body") or ""
                if "Autopilot journey card" in body and "SUPERSEDED" not in body:
                    row["card"] = {"url": f"{issue['web_url']}#note_{n['id']}", **card_numbers(body)}
                if "Autopilot journey" in body and "narrative" in body.lower() and "journey card" not in body.lower():
                    row["narrative_url"] = f"{issue['web_url']}#note_{n['id']}"
        except Exception as exc:  # noqa: BLE001 - notes need a token on GitLab.com
            row["notes_error"] = type(exc).__name__
        data["journeys"].append(row)
    try:
        data["security_fixes"] = [
            {
                "iid": m["iid"],
                "title": m["title"],
                "url": m["web_url"],
                "state": m["state"],
                "merged_at": m.get("merged_at"),
            }
            for m in gl.get_all("merge_requests", labels="security-fix", state="all")
        ]
    except Exception as exc:  # noqa: BLE001
        warn(f"security-fix MRs: {type(exc).__name__}")
        data["security_fixes"] = []
    try:
        data["incidents"] = [
            {
                "iid": i["iid"],
                "title": i["title"],
                "url": i["web_url"],
                "state": i["state"],
                "created_at": i.get("created_at"),
                "labels": i.get("labels", []),
            }
            for i in gl.get_all("issues", issue_type="incident", state="all")
        ]
    except Exception as exc:  # noqa: BLE001
        warn(f"incidents: {type(exc).__name__}")
        data["incidents"] = []
    return data


def _a(url: str | None, text: str) -> str:
    return f'<a href="{html.escape(url)}">{html.escape(text)}</a>' if url else html.escape(text)


def _d(ts: str | None) -> str:
    return html.escape((ts or "")[:16].replace("T", " ") + ("Z" if ts else "—"))


def render(data: dict) -> str:
    rows = []
    for j in data.get("journeys", []):
        card = j.get("card") or {}
        mr = j.get("mr") or {}
        issue_link = _a(j["url"], f"#{j['iid']}")
        mr_cell = (
            (_a(mr.get("url"), f"!{mr['iid']}") + "<br><small>" + _d(mr.get("merged_at")) + "</small>") if mr else "—"
        )
        if card:
            evidence = _a(card.get("url"), "card")
        else:
            evidence = "notes need sign-in" if j.get("notes_error") else "—"
        evidence += " · " + (_a(j.get("narrative_url"), "narrative") if j.get("narrative_url") else "—")
        footprint = (
            f"{html.escape(str(card.get('runner_minutes', '—')))} min · {html.escape(str(card.get('g_co2e', '—')))} g"
        )
        rows.append(
            "<tr>"
            f"<td>{issue_link}<br><small>{html.escape(j['title'])}</small></td>"
            f"<td>@{html.escape(j.get('author', ''))}<br><small>{_d(j.get('created_at'))}</small></td>"
            f"<td>{mr_cell}</td>"
            f"<td>{html.escape(str(card.get('stages', '—')))}/9</td>"
            f"<td>{html.escape(str(card.get('lead_time', '—')))}</td>"
            f"<td>{html.escape(str(card.get('human_actions', '—')))}</td>"
            f"<td>{footprint}</td>"
            f"<td>{evidence}</td>"
            "</tr>"
        )
    sec = "".join(
        f"<li>{_a(m['url'], '!' + str(m['iid']) + ' ' + m['title'])} — {html.escape(m['state'])} {_d(m.get('merged_at'))}</li>"
        for m in data.get("security_fixes", [])
    )
    inc = "".join(
        f"<li>{_a(i['url'], '#' + str(i['iid']) + ' ' + i['title'])} — {html.escape(i['state'])}, {_d(i.get('created_at'))}, "
        f"{html.escape(', '.join(i.get('labels', [])))}</li>"
        for i in data.get("incidents", [])
    )
    n = len(data.get("journeys", []))
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Autopilot receipts</title>
<style>
:root{{--fg:#1f1f1f;--muted:#666;--line:#e0e0e0;--bg:#fff;--acc:#1f75cb}}
@media (prefers-color-scheme:dark){{:root{{--fg:#eee;--muted:#aaa;--line:#333;--bg:#121212;--acc:#7ab8ff}}}}
body{{font:15px/1.5 system-ui,sans-serif;color:var(--fg);background:var(--bg);margin:0;padding:16px;max-width:1100px;margin-inline:auto}}
table{{border-collapse:collapse;width:100%;font-size:14px}} th,td{{border-bottom:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}}
small{{color:var(--muted)}} a{{color:var(--acc)}} h1{{font-size:22px}} h2{{font-size:17px;margin-top:28px}}
.wrap{{overflow-x:auto}} footer{{color:var(--muted);font-size:13px;margin-top:32px}}
</style></head><body>
<h1>Autopilot — receipts</h1>
<p>Every <code>autopilot</code> journey in {_a(data.get("project"), data.get("project", ""))}, read from GitLab by
<code>scripts/receipts_page.py</code> on {_d(data.get("generated_at"))}. Each cell links to the GitLab page it was read from;
nothing on this page is typed by hand. Numbers come from the journey card the <code>journey-card</code> CI job posted
(lead time = issue created → production deployed; human actions = non-system notes, approvals and MR commits by human
accounts after filing; CI footprint = an estimate, <code>docs/SCI.md</code>).</p>
<h2>{n} journey{"s" if n != 1 else ""}</h2>
<div class="wrap"><table><thead><tr><th>issue</th><th>filed by</th><th>merge request</th><th>stages</th><th>lead time</th>
<th>human actions after filing</th><th>CI footprint</th><th>evidence</th></tr></thead>
<tbody>{"".join(rows) or '<tr><td colspan="8">no autopilot issues yet</td></tr>'}</tbody></table></div>
<h2>Security-fix merge requests</h2><ul>{sec or "<li>none yet</li>"}</ul>
<h2>Incidents</h2><ul>{inc or "<li>none yet</li>"}</ul>
<footer>Policy: <code>AUTOPILOT.md</code> (judging freeze §1.3 after 2026-10-27 13:00 UTC). Generated by the <code>pages</code> job;
raw input: <a href="receipts.json">receipts.json</a>.</footer>
</body></html>
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="public")
    ap.add_argument("--project", default=os.environ.get("CI_PROJECT_ID"))
    ap.add_argument("--from-json", help="offline: render a saved receipts.json instead of calling the API")
    args = ap.parse_args(argv)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.from_json:
        data = json.loads(Path(args.from_json).read_text(encoding="utf-8"))
    else:
        if not args.project:
            print("no project id; nothing to read")
            return 0
        data = collect(GitLab(project=str(args.project)))
    (out / "receipts.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    (out / "index.html").write_text(render(data), encoding="utf-8")
    print(f"{out / 'index.html'}: {len(data.get('journeys', []))} journeys, {len(data.get('incidents', []))} incidents")
    return 0


if __name__ == "__main__":
    sys.exit(main())
